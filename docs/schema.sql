CREATE TABLE `CLUB` (
	`CLUB_ID` BIGINT NOT NULL COMMENT '클럽 ID' AUTO_INCREMENT, 
	`CLUB_SLUG` VARCHAR(50) NOT NULL COMMENT '클럽 URL 주소(공개 조회/관리자 진입 경로)', 
	`CLUB_NAME` VARCHAR(100) NOT NULL COMMENT '클럽명', 
	`SPORT_TYPE` VARCHAR(20) NOT NULL COMMENT '종목(현재 FUTSAL만 업무 규칙 구현)', 
	`TIMEZONE` VARCHAR(50) NOT NULL COMMENT '표시용 시간대(기본 Asia/Seoul)', 
	`CONFIG_VERSION` INTEGER NOT NULL COMMENT '운영 설정 버전(SYSTEM_CONFIG 변경마다 +1)', 
	`ACTIVE_YN` BOOL NOT NULL COMMENT '사용 여부(false=비활성, 삭제 대신 사용)', 
	`UPDATED_AT` DATETIME(3) NOT NULL COMMENT '수정 일시(UTC)', 
	`CREATED_AT` DATETIME(3) NOT NULL COMMENT '생성 일시(UTC)', 
	CONSTRAINT `PK_CLUB` PRIMARY KEY (`CLUB_ID`), 
	CONSTRAINT `UQ_CLUB_CLUB_SLUG` UNIQUE (`CLUB_SLUG`)
