def apply_comments(metadata: MetaData) -> None:
    for table in metadata.tables.values():
        spec = COMMENTS.get(table.name, {})
        if "__table__" in spec:
            table.comment = spec["__table__"]
        for col in table.columns:
            text = spec.get(col.name) or COMMON.get(col.name)
            if text:
                col.comment = text
